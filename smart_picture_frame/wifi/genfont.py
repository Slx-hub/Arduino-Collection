FIRST, LAST = 32, 90

missing = [chr(c) for c in range(FIRST, LAST + 1) if chr(c) not in G]
if missing:
    sys.exit('missing glyphs: %r' % missing)
for ch, rows in G.items():
    if len(rows) != 7:
        sys.exit('bad row count for %r' % ch)
    if any(len(r) != 5 for r in rows):
        sys.exit('bad width for %r' % ch)
    if any(set(r) - set('.#') for r in rows):
        sys.exit('bad chars in %r' % ch)

if '--preview' in sys.argv:
    chars = [chr(c) for c in range(FIRST, LAST + 1)]
    per = 16
    for i in range(0, len(chars), per):
        chunk = chars[i:i + per]
        print('   '.join('  %s  ' % c for c in chunk))
        for r in range(7):
            print('   '.join(G[c][r].replace('#', '#').replace('.', ' ') + ' ' for c in chunk))
        print()
    sys.exit(0)

out = []
out.append('// font5x7.h -- generated, do not edit by hand (see scratchpad/genfont.py)')
out.append('// 5x7 glyphs for ASCII %d..%d, one byte per row, bits 4..0 = left..right.' % (FIRST, LAST))
out.append('#pragma once')
out.append('#include <Arduino.h>')
out.append('')
out.append('#define FONT_FIRST_CHAR %d' % FIRST)
out.append('#define FONT_LAST_CHAR  %d' % LAST)
out.append('#define FONT_WIDTH      5')
out.append('#define FONT_HEIGHT     7')
out.append('')
out.append('const uint8_t FONT5X7[][FONT_HEIGHT] = {')
for c in range(FIRST, LAST + 1):
    ch = chr(c)
    bits = ['0x%02X' % int(r.replace('.', '0').replace('#', '1'), 2) for r in G[ch]]
    label = 'space' if ch == ' ' else ch
    out.append('  {%s}, // %s' % (', '.join(bits), label))
out.append('};')
out.append('')
io.open('font5x7.h', 'w', encoding='utf-8', newline='').write('\r\n'.join(out))
print('wrote font5x7.h: %d glyphs' % (LAST - FIRST + 1))
